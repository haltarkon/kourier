/// The pseudo-language as PO text: every message of `template` wrapped in `xx` … `xx` (what
/// KDE's `x-test` does), placeholders untouched, both plural forms.
pub fn pseudo_po(template: &[Entry]) -> String {
    let mut out = String::from(
        "msgid \"\"\nmsgstr \"\"\n\"Language: x-test\\n\"\n\"Content-Type: text/plain; charset=UTF-8\\n\"\n\"Content-Transfer-Encoding: 8bit\\n\"\n\"Plural-Forms: nplurals=2; plural=(n != 1);\\n\"\n",
    );
    for e in template.iter().skip(1) {
        let wrap = |s: &str| format!("xx{s}xx");
        let p = Entry {
            refs: Vec::new(),
            comments: Vec::new(),
            flags: e.flags.clone(),
            context: e.context.clone(),
            msgid: e.msgid.clone(),
            plural: e.plural.clone(),
            strs: match &e.plural {
                Some(plural) => vec![wrap(&e.msgid), wrap(plural)],
                None => vec![wrap(&e.msgid)],
            },
        };
        out.push('\n');
        out.push_str(&p.to_po(2));
    }
    out
}

/// Compiles the translations of `po/LINGUAS` and the pseudo-language into `out`.
pub fn build(out: &Path) -> Result<()> {
    let root = root();
    let template_text = std::fs::read_to_string(root.join("po/kourier.pot"))
        .context("read po/kourier.pot (cargo xtask i18n extract writes it)")?;
    let template = parse_po(&template_text)?;
    let mut built = Vec::new();
    let mut compile = |lang: &str, po: &Path| -> Result<()> {
        let mo = out.join(lang).join("LC_MESSAGES/kourier.mo");
        std::fs::create_dir_all(mo.parent().context("a directory")?)?;
        let mut cmd = Command::new("msgfmt");
        cmd.arg("-c").arg("-o").arg(&mo).arg(po);
        run_tool(&mut cmd)?;
        built.push(lang.to_owned());
        Ok(())
    };
    for lang in linguas()? {
        compile(&lang, &root.join(format!("po/{lang}.po")))?;
    }
    let work = root.join("target/i18n");
    std::fs::create_dir_all(&work)?;
    let pseudo = work.join("x-test.po");
    std::fs::write(&pseudo, pseudo_po(&template))?;
    compile(PSEUDO, &pseudo)?;
    eprintln!(
        "i18n build: {} into {} (run with LANGUAGE=x-test KOURIER_LOCALE_DIR={})",
        built.join(", "),
        out.display(),
        out.display()
    );
    Ok(())
}

