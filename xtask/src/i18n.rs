/// KUIT markup (KDE's `xi18n*` tags): not used, so that plain gettext reads the catalog.
const KUIT_TAGS: &[&str] = &[
    "para",
    "title",
    "subtitle",
    "list",
    "item",
    "note",
    "warning",
    "filename",
    "link",
    "application",
    "command",
    "resource",
    "icode",
    "bcode",
    "email",
    "emphasis",
    "placeholder",
    "numid",
    "nl",
    "envar",
    "message",
    "shortcut",
    "interface",
];

fn has_kuit_tag(s: &str) -> bool {
    let mut rest = s;
    while let Some(i) = rest.find('<') {
        let tail = rest[i + 1..].trim_start_matches('/');
        let name: String = tail
            .chars()
            .take_while(|c| c.is_ascii_alphabetic())
            .collect();
        let after = tail[name.len()..].chars().next();
        if KUIT_TAGS.contains(&name.as_str()) && matches!(after, Some('>' | ' ' | '/')) {
            return true;
        }
        rest = &rest[i + 1..];
    }
    false
}

/// A `{n}`, `{0}`, `{name}` or `{}` placeholder (the spelling of other i18n systems).
fn has_brace_placeholder(s: &str) -> bool {
    let mut rest = s;
    while let Some(i) = rest.find('{') {
        let tail = &rest[i + 1..];
        if let Some(close) = tail.find('}')
            && tail[..close]
                .chars()
                .all(|c| c.is_ascii_alphanumeric() || matches!(c, '_' | ',' | ' '))
        {
            return true;
        }
        rest = tail;
    }
    false
}

/// The `%1`…`%9` placeholders of a text, as digits, sorted and without repeats.
pub fn placeholders(s: &str) -> Vec<char> {
    let b = s.as_bytes();
    let mut out = Vec::new();
    for i in 0..b.len() {
        if b[i] == b'%'
            && b.get(i + 1).is_some_and(|d| (b'1'..=b'9').contains(d))
            && !b.get(i + 2).is_some_and(u8::is_ascii_digit)
        {
            out.push(char::from(b[i + 1]));
        }
    }
    out.sort_unstable();
    out.dedup();
    out
}

/// The languages of `po/LINGUAS`.
pub fn linguas() -> Result<Vec<String>> {
    let path = root().join("po/LINGUAS");
    let text = std::fs::read_to_string(&path).with_context(|| {
        format!(
            "read {} (cargo xtask i18n extract creates it)",
            path.display()
        )
    })?;
    Ok(text
        .lines()
        .map(|l| l.split('#').next().unwrap_or_default().trim())
        .filter(|l| !l.is_empty())
        .flat_map(|l| l.split_whitespace().map(str::to_owned).collect::<Vec<_>>())
        .collect())
}

/// What is wrong with the entries of a template (the rules of the project, §8.10 R4).
fn template_problems(entries: &[Entry]) -> Vec<String> {
    let mut problems = Vec::new();
    for e in entries.iter().skip(1) {
        let place = e.refs.first().map_or("?", String::as_str);
        let shown = format!("“{}” ({place})", e.msgid);
        let packaging_only =
            !e.refs.is_empty() && e.refs.iter().all(|r| r.starts_with("packaging/"));
        if e.context.as_deref().is_none_or(str::is_empty) && !packaging_only {
            problems.push(format!(
                "{shown} has no context: use i18nc(\"@info\", …) or trc(\"@info\", …) with a KDE context marker"
            ));
        }
        if let Some(c) = e
            .context
            .as_deref()
            .filter(|c| !c.is_empty() && !c.starts_with('@'))
        {
            problems.push(format!(
                "{shown}: the context “{c}” does not start with a KDE marker (@info, @action:button, …)"
            ));
        }
        for text in std::iter::once(&e.msgid).chain(e.plural.as_ref()) {
            if has_kuit_tag(text) {
                problems.push(format!(
                    "{shown} uses KUIT tags; the catalog is plain gettext"
                ));
            }
            if has_brace_placeholder(text) {
                problems.push(format!("{shown} uses a {{…}} placeholder; use %1…%9"));
            }
        }
    }
    problems
}

/// What is wrong with one translation file: its strings against the template's. The second
/// part of `msgfmt -c` is run by the caller.
fn translation_problems(lang: &str, template: &[Entry], po: &[Entry]) -> Vec<String> {
    let mut problems = Vec::new();
    let source: BTreeMap<(Option<&str>, &str), &Entry> = template
        .iter()
        .skip(1)
        .map(|e| ((e.context.as_deref(), e.msgid.as_str()), e))
        .collect();
    for e in po.iter().skip(1) {
        if e.strs.iter().all(String::is_empty) || e.flags.iter().any(|f| f == "fuzzy") {
            continue;
        }
        let Some(src) = source.get(&(e.context.as_deref(), e.msgid.as_str())) else {
            // The template lost this message: msgmerge marks it obsolete on its next run.
            continue;
        };
        let mut want = placeholders(&src.msgid);
        if let Some(p) = &src.plural {
            want.extend(placeholders(p));
            want.sort_unstable();
            want.dedup();
        }
        for (form, text) in e.strs.iter().enumerate() {
            if text.is_empty() {
                continue;
            }
            let mut got = placeholders(text);
            // A plural form that is used for one number only may say it in words ("one
            // file"): it may leave out the count, %1, and nothing else.
            if src.plural.is_some() {
                let mut with_count = got.clone();
                if !with_count.contains(&'1') && want.contains(&'1') {
                    with_count.push('1');
                    with_count.sort_unstable();
                }
                if with_count == want {
                    got = with_count;
                }
            }
            if got != want {
                problems.push(format!(
                    "po/{lang}.po: “{}”{}: the translation has the placeholders {} and the source {}",
                    e.msgid,
                    if src.plural.is_some() { format!(" (form {form})") } else { String::new() },
                    show_placeholders(&got),
                    show_placeholders(&want)
                ));
            }
        }
        if let Some(p) = &src.plural
            && e.strs.len() < 2
        {
            problems.push(format!("po/{lang}.po: “{p}” has no plural forms"));
        }
    }
    problems
}

fn show_placeholders(p: &[char]) -> String {
    if p.is_empty() {
        "none".to_owned()
    } else {
        p.iter()
            .map(|d| format!("%{d}"))
            .collect::<Vec<_>>()
            .join(" ")
    }
}

fn check() -> Result<()> {
    let mut problems = Vec::new();
    let (fresh, _) = make_template()?;
    let pot_path = root().join("po/kourier.pot");
    let committed = std::fs::read_to_string(&pot_path).unwrap_or_default();
    if committed != fresh {
        let old = parse_po(&committed).unwrap_or_default();
        let new = parse_po(&fresh)?;
        let key = |e: &Entry| (e.context.clone(), e.msgid.clone());
        let old_keys: std::collections::BTreeSet<_> = old.iter().map(key).collect();
        let new_keys: std::collections::BTreeSet<_> = new.iter().map(key).collect();
        let added: Vec<_> = new_keys.difference(&old_keys).take(5).collect();
        let removed: Vec<_> = old_keys.difference(&new_keys).take(5).collect();
        problems.push(format!(
            "po/kourier.pot is not what `cargo xtask i18n extract` writes now ({} messages added, {} removed, e.g. {:?} / {:?}); run it and commit the result",
            new_keys.difference(&old_keys).count(),
            old_keys.difference(&new_keys).count(),
            added.first().map(|k| &k.1),
            removed.first().map(|k| &k.1),
        ));
    }
    let template = parse_po(&fresh)?;
    problems.extend(template_problems(&template));

    let langs = linguas()?;
    let mut progress = Vec::new();
    for lang in &langs {
        let path = root().join(format!("po/{lang}.po"));
        let text = match std::fs::read_to_string(&path) {
            Ok(t) => t,
            Err(_) => {
                problems.push(format!(
                    "po/LINGUAS lists {lang}, and po/{lang}.po is not there"
                ));
                continue;
            }
        };
        let out = Command::new("msgfmt")
            .arg("-c")
            .arg("-o")
            .arg("/dev/null")
            .arg(&path)
            .output()
            .context("run msgfmt (apt install gettext)")?;
        if !out.status.success() {
            problems.push(format!(
                "msgfmt -c po/{lang}.po:\n{}",
                String::from_utf8_lossy(&out.stderr).trim_end()
            ));
        }
        match parse_po(&text) {
            Ok(po) => {
                problems.extend(translation_problems(lang, &template, &po));
                let (done, all) = translated(&template, &po);
                progress.push(format!("{lang} {done}/{all}"));
            }
            Err(e) => problems.push(format!("po/{lang}.po cannot be read: {e:#}")),
        }
    }
    if problems.is_empty() {
        // An untranslated message is no problem (the application shows English): the
        // numbers say how far each language is.
        eprintln!(
            "i18n check: {} messages, {} language(s) in po/LINGUAS{}: ok",
            template.len().saturating_sub(1),
            langs.len(),
            if progress.is_empty() {
                String::new()
            } else {
                format!(" ({})", progress.join(", "))
            }
        );
        return Ok(());
    }
    for p in problems.iter().take(40) {
        eprintln!("i18n check: {p}");
    }
    if problems.len() > 40 {
        eprintln!("i18n check: … and {} more", problems.len() - 40);
    }
    bail!("i18n check: {} problem(s)", problems.len())
}

