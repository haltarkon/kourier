//! `cargo xtask i18n <extract|check|build>`: the translation catalog (architecture §9.5,
//! §14.2 item 11; the guide for translators is `TRANSLATING.md`).
//!
//! One gettext domain, `kourier`, one template, `po/kourier.pot`, for every string of the
//! application:
//!
//! - QML: `L10n.i18nc(…)` and QML's own `i18n*()` functions, read by `xgettext -L JavaScript`;
//! - Rust: the calls of `kourier_viewmodel::i18n` (`trc`, `trnc`, `trfc`, `trc_noop`), read by
//!   the small reader below, because GNU xgettext has no Rust parser before 0.24;
//! - the desktop file (`Name`, `GenericName`, `Comment`, `Keywords`) and the AppStream
//!   metainfo (`xgettext` with gettext's `metainfo.its` rules).
//!
//! `extract` writes the template, `check` fails when it is out of date or breaks a rule of the
//! project (a context for every string, no KUIT tags, no `{…}` placeholders, translations that
//! compile and keep the placeholders), `build` compiles `po/<lang>.po` of `po/LINGUAS` into
//! `target/locale/<lang>/LC_MESSAGES/kourier.mo` and writes the pseudo-language `x-test`.
//!
//! The output is kept small in diffs: sources are named by file without line numbers, entries
//! are sorted by file, nothing is wrapped and there is no creation date.

use anyhow::{Context, Result, bail};
use std::collections::BTreeMap;
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::root;

const USAGE: &str = "usage: cargo xtask i18n <extract|check|build [--out <dir>]>

  extract              write po/kourier.pot from the QML files, the Rust call sites, the desktop
                       file and the metainfo
  check                fail when po/kourier.pot is out of date, a string breaks the rules, or a
                       translation of po/LINGUAS does not compile or changes the placeholders
  build [--out <dir>]  compile the translations of po/LINGUAS and the pseudo-language x-test to
                       <dir>/<lang>/LC_MESSAGES/kourier.mo (default: target/locale)";

/// The pseudo-language: each message is wrapped as KDE's `x-test` does.
pub const PSEUDO: &str = "x-test";

/// The Rust files that the extractor does not read: the module that defines the functions
/// (its tests use made-up messages).
const RUST_SKIP: &[&str] = &["crates/kourier-viewmodel/src/i18n.rs"];

/// The directories of QML files and the directories of Rust sources, below the repository.
const QML_DIR: &str = "crates/kourier-qt/qml";
const RUST_CRATES_DIR: &str = "crates";

/// `xgettext` keywords of the QML functions: `L10n.i18nc(…)` and the engine's own `i18n*()`.
const QML_KEYWORDS: &[&str] = &[
    "i18n:1",
    "i18np:1,2",
    "i18nc:1c,2",
    "i18ncp:1c,2,3",
    "i18nd:2",
    "i18ndp:2,3",
    "i18ndc:2c,3",
    "i18ndcp:2c,3,4",
];

/// The functions of `kourier_viewmodel::i18n` the Rust reader looks for, with the position of
/// the context (always 0) and of the message ids that follow it.
const RUST_KEYWORDS: &[(&str, usize)] = &[("trc", 1), ("trfc", 1), ("trnc", 2), ("trc_noop", 1)];

/// The header of the template: written by this tool, not by `xgettext`, so that it has no date.
const POT_HEADER: &str = "# Translation template of Kourier (gettext domain \"kourier\").
# Generated by `cargo xtask i18n extract`; do not edit it by hand.
# This file is distributed under the same license as the Kourier package (AGPL-3.0-only).
#
msgid \"\"
msgstr \"\"
\"Project-Id-Version: kourier\\n\"
\"Report-Msgid-Bugs-To: \\n\"
\"MIME-Version: 1.0\\n\"
\"Content-Type: text/plain; charset=UTF-8\\n\"
\"Content-Transfer-Encoding: 8bit\\n\"
\"Plural-Forms: nplurals=INTEGER; plural=EXPRESSION;\\n\"
";

/// Content of `po/LINGUAS` when it is created: no language yet.
const LINGUAS_EMPTY: &str = "# The languages of the application: one code per line, each with a po/<code>.po.\n\
# The codes are the ones of glibc and KDE (de, pt_BR, zh_CN, sr@latin), not BCP 47.\n";

pub fn i18n(args: &[String]) -> Result<()> {
    match args.first().map(String::as_str) {
        Some("extract") => extract(),
        Some("check") => check(),
        Some("build") => {
            let out = match args.get(1).map(String::as_str) {
                None => root().join("target/locale"),
                Some("--out") => {
                    let dir = args.get(2).context("--out needs a directory")?;
                    std::path::absolute(dir).with_context(|| format!("make {dir} absolute"))?
                }
                Some(other) => bail!("unknown argument {other}\n{USAGE}"),
            };
            build(&out)
        }
        _ => bail!("{USAGE}"),
    }
}

// ---------------------------------------------------------------------------------------
// extract

fn extract() -> Result<()> {
    let (pot, packaged) = make_template()?;
    if packaged > 0 {
        eprintln!("i18n extract: {packaged} lookup(s) of strings that the packaging files hold");
    }
    let dest = root().join("po/kourier.pot");
    std::fs::create_dir_all(root().join("po"))?;
    std::fs::write(&dest, &pot).with_context(|| format!("write {}", dest.display()))?;
    let linguas_file = root().join("po/LINGUAS");
    if !linguas_file.exists() {
        std::fs::write(&linguas_file, LINGUAS_EMPTY)?;
    }
    let entries = parse_po(&pot)?.len().saturating_sub(1);
    eprintln!("i18n extract: {entries} messages in po/kourier.pot");
    // The translations follow the template: a new message arrives untranslated, a changed
    // one is marked fuzzy with its old source beside it (the application shows English for
    // both until a translator has looked), a removed one moves to the obsolete entries.
    for lang in linguas()? {
        let po = root().join(format!("po/{lang}.po"));
        if !po.exists() {
            continue;
        }
        run_tool(
            Command::new("msgmerge")
                .args(["--update", "--backup=none", "--quiet", "--previous"])
                .args(["--no-wrap", "--add-location=file"])
                .arg(&po)
                .arg(&dest),
        )?;
        let text = std::fs::read_to_string(&po)?;
        let (done, all) = translated(&parse_po(&pot)?, &parse_po(&text)?);
        eprintln!("i18n extract: po/{lang}.po merged, {done} of {all} translated");
    }
    Ok(())
}

/// How many messages of `template` the translation `po` translates (fuzzy ones do not
/// count: gettext does not use them), and how many the template has.
fn translated(template: &[Entry], po: &[Entry]) -> (usize, usize) {
    let done: std::collections::BTreeSet<(Option<&str>, &str)> = po
        .iter()
        .skip(1)
        .filter(|e| !e.strs.iter().any(String::is_empty) && !e.flags.iter().any(|f| f == "fuzzy"))
        .map(|e| (e.context.as_deref(), e.msgid.as_str()))
        .collect();
    let all = template.iter().skip(1);
    (
        all.clone()
            .filter(|e| done.contains(&(e.context.as_deref(), e.msgid.as_str())))
            .count(),
        all.count(),
    )
}

/// The text `extract` writes now, and the number of Rust lookups of text that the packaging
/// files hold (they have no call site to extract).
fn make_template() -> Result<(String, usize)> {
    let root = root();
    let work = root.join("target/i18n");
    std::fs::create_dir_all(&work)?;

    // QML.
    let mut qml = files_below(&root.join(QML_DIR), "qml")?;
    qml.sort();
    let qml_list: String = qml.iter().map(|p| format!("{}\n", rel(p))).collect();
    std::fs::write(work.join("qml.list"), qml_list)?;
    let mut cmd = Command::new("xgettext");
    cmd.current_dir(&root)
        .args(["--from-code=UTF-8", "-L", "JavaScript", "-k"])
        .args(QML_KEYWORDS.iter().map(|k| format!("-k{k}")))
        .args([
            "--add-comments=TRANSLATORS:",
            "--no-wrap",
            "--files-from=target/i18n/qml.list",
        ])
        .args(["-o", "target/i18n/qml.pot"]);
    run_tool(&mut cmd)?;

    // Rust.
    let mut rust = Vec::new();
    for krate in sorted_dirs(&root.join(RUST_CRATES_DIR))? {
        rust.extend(files_below(&krate.join("src"), "rs")?);
    }
    rust.sort();
    let (rust_pot, packaged) = rust_template(&root, &rust)?;
    std::fs::write(work.join("rust.pot"), rust_pot)?;

    // The strings of the interface get the format flag KI18n's placeholders need.
    let mut cmd = Command::new("msgcat");
    cmd.current_dir(&root)
        .args(["--no-wrap", "--sort-by-file", "-o", "target/i18n/ui.pot"])
        .args(["target/i18n/qml.pot", "target/i18n/rust.pot"]);
    run_tool(&mut cmd)?;
    let ui = parse_po(&std::fs::read_to_string(work.join("ui.pot"))?)?;
    std::fs::write(work.join("ui-flagged.pot"), flag_kde_format(&ui))?;

    // The desktop file and the metainfo.
    let mut packaging: Vec<PathBuf> = Vec::new();
    let mut desktop_pots = Vec::new();
    for entry in std::fs::read_dir(root.join("packaging"))? {
        let path = entry?.path();
        let name = path
            .file_name()
            .and_then(|n| n.to_str())
            .unwrap_or_default();
        if name.ends_with(".desktop") || name.ends_with(".metainfo.xml") {
            packaging.push(path);
        }
    }
    packaging.sort();
    for (i, file) in packaging.iter().enumerate() {
        let out = format!("target/i18n/packaging-{i}.pot");
        let mut cmd = Command::new("xgettext");
        cmd.current_dir(&root)
            .args(["--no-wrap", "--from-code=UTF-8"]);
        if file.extension().is_some_and(|e| e == "desktop") {
            cmd.args(["-L", "Desktop"]);
        }
        cmd.args(["-o", &out]).arg(rel(file));
        run_tool(&mut cmd)?;
        desktop_pots.push(out);
    }

    let mut cmd = Command::new("msgcat");
    cmd.current_dir(&root)
        .args(["--no-wrap", "--sort-by-file", "--add-location=file"])
        .args(["-o", "target/i18n/all.pot", "target/i18n/ui-flagged.pot"])
        .args(&desktop_pots);
    run_tool(&mut cmd)?;
    let merged = std::fs::read_to_string(work.join("all.pot"))?;
    // msgcat's own header (a date, package placeholders) is replaced by ours.
    let body = merged
        .split_once("\n\n")
        .map(|(_, rest)| rest)
        .context("msgcat wrote no header")?;
    Ok((format!("{POT_HEADER}\n{body}"), packaged))
}

/// The messages of the interface as PO text, each with the flag `kde-format`: KI18n's `%1`
/// placeholders, which `msgfmt -c` then checks in the translations (gettext 0.21's
/// `msgattrib` cannot set a flag, and `xgettext` sets it for C++ only).
fn flag_kde_format(entries: &[Entry]) -> String {
    let mut out = String::from(
        "msgid \"\"\nmsgstr \"\"\n\"Content-Type: text/plain; charset=UTF-8\\n\"\n\"Plural-Forms: nplurals=INTEGER; plural=EXPRESSION;\\n\"\n",
    );
    for e in entries.iter().skip(1) {
        let mut e = e.clone();
        if !e.flags.iter().any(|f| f == "kde-format") {
            e.flags.push("kde-format".to_owned());
        }
        out.push('\n');
        out.push_str(&e.to_po(2));
    }
    out
}

fn run_tool(cmd: &mut Command) -> Result<()> {
    let name = cmd.get_program().to_string_lossy().into_owned();
    let out = cmd.output().with_context(|| {
        format!("run {name}: it comes with the package `gettext` (apt install gettext)")
    })?;
    if !out.status.success() {
        bail!(
            "{name} failed ({}):\n{}",
            out.status,
            String::from_utf8_lossy(&out.stderr)
        );
    }
    Ok(())
}

/// `path` relative to the repository, with `/`.
fn rel(path: &Path) -> String {
    path.strip_prefix(root())
        .unwrap_or(path)
        .to_string_lossy()
        .into_owned()
}

fn sorted_dirs(dir: &Path) -> Result<Vec<PathBuf>> {
    let mut out = Vec::new();
    for entry in std::fs::read_dir(dir)? {
        let path = entry?.path();
        if path.is_dir() {
            out.push(path);
        }
    }
    out.sort();
    Ok(out)
}

/// Every file with the extension `ext` below `dir` (nothing when `dir` is not there).
fn files_below(dir: &Path, ext: &str) -> Result<Vec<PathBuf>> {
    let mut out = Vec::new();
    if !dir.is_dir() {
        return Ok(out);
    }
    let mut stack = vec![dir.to_path_buf()];
    while let Some(d) = stack.pop() {
        for entry in std::fs::read_dir(&d)? {
            let path = entry?.path();
            if path.is_dir() {
                stack.push(path);
            } else if path.extension().is_some_and(|e| e == ext) {
                out.push(path);
            }
        }
    }
    Ok(out)
}

