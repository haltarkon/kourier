// A small reader and writer of PO files

/// A message of a `.po` or `.pot`.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Entry {
    pub refs: Vec<String>,
    /// Extracted comments (`#.`).
    pub comments: Vec<String>,
    pub flags: Vec<String>,
    pub context: Option<String>,
    pub msgid: String,
    pub plural: Option<String>,
    /// `msgstr`, or `msgstr[0]`, `msgstr[1]`, …
    pub strs: Vec<String>,
}

impl Entry {
    /// The entry as PO text with `forms` empty plural forms when it has none yet (every
    /// string on one line: wrapping is the job of gettext's tools).
    fn to_po(&self, forms: usize) -> String {
        let mut out = String::new();
        for c in &self.comments {
            out.push_str("#. ");
            out.push_str(c);
            out.push('\n');
        }
        for r in &self.refs {
            out.push_str("#: ");
            out.push_str(r);
            out.push('\n');
        }
        if !self.flags.is_empty() {
            out.push_str(&format!("#, {}\n", self.flags.join(", ")));
        }
        if let Some(c) = &self.context {
            out.push_str(&format!("msgctxt {}\n", po_quote(c)));
        }
        out.push_str(&format!("msgid {}\n", po_quote(&self.msgid)));
        match &self.plural {
            Some(p) => {
                out.push_str(&format!("msgid_plural {}\n", po_quote(p)));
                for n in 0..forms.max(self.strs.len()) {
                    let s = self.strs.get(n).map_or("", String::as_str);
                    out.push_str(&format!("msgstr[{n}] {}\n", po_quote(s)));
                }
            }
            None => {
                let s = self.strs.first().map_or("", String::as_str);
                out.push_str(&format!("msgstr {}\n", po_quote(s)));
            }
        }
        out
    }
}

fn po_quote(s: &str) -> String {
    let mut out = String::from("\"");
    for ch in s.chars() {
        match ch {
            '\\' => out.push_str("\\\\"),
            '"' => out.push_str("\\\""),
            '\n' => out.push_str("\\n"),
            '\t' => out.push_str("\\t"),
            '\r' => out.push_str("\\r"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn po_unquote(s: &str) -> Result<String> {
    let s = s.trim();
    let inner = s
        .strip_prefix('"')
        .and_then(|s| s.strip_suffix('"'))
        .with_context(|| format!("not a PO string: {s}"))?;
    let mut out = String::new();
    let mut chars = inner.chars();
    while let Some(c) = chars.next() {
        if c != '\\' {
            out.push(c);
            continue;
        }
        match chars.next() {
            Some('n') => out.push('\n'),
            Some('t') => out.push('\t'),
            Some('r') => out.push('\r'),
            Some('"') => out.push('"'),
            Some('\\') => out.push('\\'),
            other => bail!("unknown escape in a PO string: \\{other:?}"),
        }
    }
    Ok(out)
}

/// Reads a `.po`/`.pot` text. The first entry is the header (an empty message id).
pub fn parse_po(text: &str) -> Result<Vec<Entry>> {
    #[derive(PartialEq)]
    enum Field {
        None,
        Ctx,
        Id,
        Plural,
        Str(usize),
    }
    let mut entries = Vec::new();
    let mut cur = Entry::default();
    let mut started = false;
    let mut field = Field::None;
    let mut flush = |cur: &mut Entry, started: &mut bool| {
        if *started {
            entries.push(std::mem::take(cur));
        }
        *started = false;
    };
    for (n, line) in text.lines().enumerate() {
        let line = line.trim_end();
        let at = || format!("line {}", n + 1);
        if line.is_empty() {
            flush(&mut cur, &mut started);
            field = Field::None;
        } else if line.starts_with("#~") {
            // An obsolete message: not ours.
        } else if let Some(rest) = line.strip_prefix("#:") {
            started = true;
            cur.refs.extend(rest.split_whitespace().map(str::to_owned));
        } else if let Some(rest) = line.strip_prefix("#.") {
            started = true;
            cur.comments.push(rest.trim().to_owned());
        } else if let Some(rest) = line.strip_prefix("#,") {
            started = true;
            cur.flags.extend(
                rest.split(',')
                    .map(|f| f.trim().to_owned())
                    .filter(|f| !f.is_empty()),
            );
        } else if line.starts_with('#') {
            started = true;
        } else if let Some(rest) = line.strip_prefix("msgctxt ") {
            started = true;
            cur.context = Some(po_unquote(rest).with_context(at)?);
            field = Field::Ctx;
        } else if let Some(rest) = line.strip_prefix("msgid_plural ") {
            cur.plural = Some(po_unquote(rest).with_context(at)?);
            field = Field::Plural;
        } else if let Some(rest) = line.strip_prefix("msgid ") {
            started = true;
            cur.msgid = po_unquote(rest).with_context(at)?;
            field = Field::Id;
        } else if let Some(rest) = line.strip_prefix("msgstr[") {
            let (index, text) = rest.split_once("] ").with_context(at)?;
            let index: usize = index.parse().with_context(at)?;
            cur.strs.resize(index + 1, String::new());
            cur.strs[index] = po_unquote(text).with_context(at)?;
            field = Field::Str(index);
        } else if let Some(rest) = line.strip_prefix("msgstr ") {
            cur.strs = vec![po_unquote(rest).with_context(at)?];
            field = Field::Str(0);
        } else if line.starts_with('"') {
            let more = po_unquote(line).with_context(at)?;
            match field {
                Field::Ctx => cur.context.get_or_insert_with(String::new).push_str(&more),
                Field::Id => cur.msgid.push_str(&more),
                Field::Plural => cur.plural.get_or_insert_with(String::new).push_str(&more),
                Field::Str(i) => cur.strs[i].push_str(&more),
                Field::None => bail!("{}: a string with no keyword", at()),
            }
        } else {
            bail!("{}: not a PO line: {line}", at());
        }
    }
    flush(&mut cur, &mut started);
    Ok(entries)
}

