// The Rust reader

/// One message found in a Rust file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Found {
    pub file: String,
    pub line: usize,
    pub context: String,
    pub msgid: String,
    pub plural: Option<String>,
    pub comment: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum Tok {
    Ident(String),
    Str(String),
    Punct(char),
    /// A literal that is no text for us (a number, a character, a byte string).
    Other,
}

#[derive(Debug, Clone)]
struct Token {
    tok: Tok,
    line: usize,
}

/// A comment: the lines it covers and its text.
#[derive(Debug, Clone)]
struct Comment {
    first: usize,
    last: usize,
    text: String,
}

/// Splits Rust source into tokens and comments: just enough of the language to find calls
/// and read their string literals (plain, raw and with escapes) without being fooled by a
/// quote inside a character literal, a comment or a raw string.
fn lex(src: &str) -> Result<(Vec<Token>, Vec<Comment>)> {
    let c: Vec<char> = src.chars().collect();
    let (mut i, mut line) = (0, 1);
    let mut toks = Vec::new();
    let mut comments = Vec::new();
    let at = |i: usize| c.get(i).copied().unwrap_or('\0');
    while i < c.len() {
        let ch = c[i];
        if ch == '\n' {
            line += 1;
            i += 1;
        } else if ch.is_whitespace() {
            i += 1;
        } else if ch == '/' && at(i + 1) == '/' {
            let start = i + 2;
            while i < c.len() && c[i] != '\n' {
                i += 1;
            }
            let text: String = c[start..i].iter().collect();
            comments.push(Comment {
                first: line,
                last: line,
                text: text.trim_start_matches(['/', '!']).trim().to_owned(),
            });
        } else if ch == '/' && at(i + 1) == '*' {
            let first = line;
            let mut depth = 1;
            let start = i + 2;
            i += 2;
            while i < c.len() && depth > 0 {
                if c[i] == '/' && at(i + 1) == '*' {
                    depth += 1;
                    i += 2;
                } else if c[i] == '*' && at(i + 1) == '/' {
                    depth -= 1;
                    i += 2;
                } else {
                    if c[i] == '\n' {
                        line += 1;
                    }
                    i += 1;
                }
            }
            let end = i.saturating_sub(2).max(start);
            let text: String = c[start..end].iter().collect();
            comments.push(Comment {
                first,
                last: line,
                text: text.trim_matches(['*', '!', ' ', '\n']).to_owned(),
            });
        } else if ch == '"' {
            let (s, next, lines) = plain_string(&c, i + 1, line)?;
            toks.push(Token {
                tok: Tok::Str(s),
                line,
            });
            line += lines;
            i = next;
        } else if ch == '\'' {
            // A character literal ('a', '\n', '"') or a lifetime ('a).
            if at(i + 1) == '\\' {
                i += 2;
                while i < c.len() && c[i] != '\'' {
                    i += 1;
                }
                i += 1;
                toks.push(Token {
                    tok: Tok::Other,
                    line,
                });
            } else if at(i + 2) == '\'' {
                i += 3;
                toks.push(Token {
                    tok: Tok::Other,
                    line,
                });
            } else {
                i += 1;
                while at(i).is_alphanumeric() || at(i) == '_' {
                    i += 1;
                }
            }
        } else if ch.is_alphabetic() || ch == '_' {
            let start = i;
            while at(i).is_alphanumeric() || at(i) == '_' {
                i += 1;
            }
            let word: String = c[start..i].iter().collect();
            // r"…", r#"…"#, b"…", br"…", c"…": a prefix directly followed by a quote.
            let raw_prefix = matches!(word.as_str(), "r" | "br" | "cr");
            let plain_prefix = matches!(word.as_str(), "b" | "c");
            if raw_prefix && (at(i) == '"' || at(i) == '#') {
                let mut hashes = 0;
                while at(i + hashes) == '#' {
                    hashes += 1;
                }
                if at(i + hashes) == '"' {
                    let body = i + hashes + 1;
                    let (s, next, lines) = raw_string(&c, body, hashes)?;
                    // A raw byte or C string is no message; a raw text is.
                    let tok = if word == "r" { Tok::Str(s) } else { Tok::Other };
                    toks.push(Token { tok, line });
                    line += lines;
                    i = next;
                    continue;
                }
            }
            if plain_prefix && at(i) == '"' {
                let (_, next, lines) = plain_string(&c, i + 1, line)?;
                toks.push(Token {
                    tok: Tok::Other,
                    line,
                });
                line += lines;
                i = next;
                continue;
            }
            if word == "b" && at(i) == '\'' {
                // A byte literal: b'a', b'\n'.
                i += 1;
                if at(i) == '\\' {
                    i += 1;
                }
                while i < c.len() && c[i] != '\'' {
                    i += 1;
                }
                i += 1;
                toks.push(Token {
                    tok: Tok::Other,
                    line,
                });
                continue;
            }
            toks.push(Token {
                tok: Tok::Ident(word),
                line,
            });
        } else if ch.is_ascii_digit() {
            while at(i).is_alphanumeric() || at(i) == '_' {
                i += 1;
            }
            toks.push(Token {
                tok: Tok::Other,
                line,
            });
        } else {
            toks.push(Token {
                tok: Tok::Punct(ch),
                line,
            });
            i += 1;
        }
    }
    Ok((toks, comments))
}

/// The body of a string literal that starts at `i` (after the opening quote): its value, the
/// index after the closing quote and the number of line breaks it spans.
fn plain_string(c: &[char], mut i: usize, line: usize) -> Result<(String, usize, usize)> {
    let mut out = String::new();
    let mut lines = 0;
    while i < c.len() {
        match c[i] {
            '"' => return Ok((out, i + 1, lines)),
            '\\' => {
                i += 1;
                match c.get(i).copied() {
                    Some('n') => out.push('\n'),
                    Some('r') => out.push('\r'),
                    Some('t') => out.push('\t'),
                    Some('0') => out.push('\0'),
                    Some('\\') => out.push('\\'),
                    Some('"') => out.push('"'),
                    Some('\'') => out.push('\''),
                    Some('x') => {
                        let hex: String = c[i + 1..(i + 3).min(c.len())].iter().collect();
                        let v = u8::from_str_radix(&hex, 16)
                            .with_context(|| format!("line {line}: bad \\x escape"))?;
                        out.push(char::from(v));
                        i += 2;
                    }
                    Some('u') => {
                        // \u{1F600}
                        let close = c[i..]
                            .iter()
                            .position(|&x| x == '}')
                            .with_context(|| format!("line {line}: bad \\u escape"))?;
                        let hex: String =
                            c[i + 2..i + close].iter().filter(|&&x| x != '_').collect();
                        let v = u32::from_str_radix(&hex, 16)
                            .ok()
                            .and_then(char::from_u32)
                            .with_context(|| format!("line {line}: bad \\u escape"))?;
                        out.push(v);
                        i += close;
                    }
                    Some('\n') => {
                        // A backslash before a line break skips the break and the
                        // indentation after it.
                        lines += 1;
                        while c.get(i + 1).is_some_and(|x| x.is_whitespace()) {
                            if c[i + 1] == '\n' {
                                lines += 1;
                            }
                            i += 1;
                        }
                    }
                    other => bail!("line {line}: unknown escape \\{other:?}"),
                }
                i += 1;
            }
            '\n' => {
                lines += 1;
                out.push('\n');
                i += 1;
            }
            ch => {
                out.push(ch);
                i += 1;
            }
        }
    }
    bail!("line {line}: a string literal is not closed")
}

/// The body of a raw string whose opening quote is just before `i`, closed by a quote and
/// `hashes` hash signs.
fn raw_string(c: &[char], mut i: usize, hashes: usize) -> Result<(String, usize, usize)> {
    let mut out = String::new();
    let mut lines = 0;
    while i < c.len() {
        if c[i] == '"' && (0..hashes).all(|h| c.get(i + 1 + h) == Some(&'#')) {
            return Ok((out, i + 1 + hashes, lines));
        }
        if c[i] == '\n' {
            lines += 1;
        }
        out.push(c[i]);
        i += 1;
    }
    bail!("a raw string literal is not closed")
}

/// The calls of the keywords in `src` (the file is named `file`). An error names the line of
/// a call whose context or message is not a string literal.
pub fn find_messages(file: &str, src: &str) -> Result<(Vec<Found>, usize)> {
    let (toks, comments) = lex(src).with_context(|| format!("read {file}"))?;
    let mut found = Vec::new();
    let mut packaged = 0;
    let mut used_comment = vec![false; comments.len()];
    for (at, t) in toks.iter().enumerate() {
        let Tok::Ident(name) = &t.tok else { continue };
        let Some(&(_, ids)) = RUST_KEYWORDS.iter().find(|(k, _)| k == name) else {
            continue;
        };
        if toks.get(at + 1).map(|n| &n.tok) != Some(&Tok::Punct('(')) {
            continue;
        }
        // A definition or a method of something else is no call of ours.
        match at.checked_sub(1).map(|p| &toks[p].tok) {
            Some(Tok::Ident(prev)) if prev == "fn" => continue,
            Some(Tok::Punct('.')) => continue,
            _ => {}
        }
        let args = split_args(&toks[at + 2..])
            .with_context(|| format!("{file}:{}: the call of {name} is not closed", t.line))?;
        let literal = |n: usize| -> Option<&str> {
            match args.get(n)?.as_slice() {
                [
                    Token {
                        tok: Tok::Str(s), ..
                    },
                ] => Some(s.as_str()),
                _ => None,
            }
        };
        let Some(context) = literal(0) else {
            bail!(
                "{file}:{}: the context of {name}(…) is not a string literal; the extractor reads literals only",
                t.line
            );
        };
        if context.is_empty() {
            // The one use of an empty context: a text that the packaging files hold (they
            // have no contexts), looked up with a variable.
            if literal(1).is_some() {
                bail!(
                    "{file}:{}: {name}(\"\", …) has no context; give the message a KDE context marker",
                    t.line
                );
            }
            packaged += 1;
            continue;
        }
        let mut ids_found = Vec::new();
        for k in 1..=ids {
            let Some(s) = literal(k) else {
                bail!(
                    "{file}:{}: argument {} of {name}(…) is not a string literal; the extractor reads literals only",
                    t.line,
                    k + 1
                );
            };
            ids_found.push(s.to_owned());
        }
        // The nearest `TRANSLATORS:` comment above the call (or on its line), used once.
        let mut comment = None;
        for (ci, c) in comments.iter().enumerate() {
            if !used_comment[ci]
                && c.text.starts_with("TRANSLATORS:")
                && c.last <= t.line
                && t.line - c.last <= 8
            {
                used_comment[ci] = true;
                let mut text = c.text.trim_start_matches("TRANSLATORS:").trim().to_owned();
                // The lines of one block comment are one remark.
                let mut next = ci + 1;
                while let Some(more) = comments.get(next) {
                    if more.first == comments[next - 1].last + 1
                        && !more.text.is_empty()
                        && !more.text.starts_with("TRANSLATORS:")
                        && more.first <= t.line
                    {
                        text.push(' ');
                        text.push_str(&more.text);
                        used_comment[next] = true;
                        next += 1;
                    } else {
                        break;
                    }
                }
                comment = Some(format!("TRANSLATORS: {text}"));
                break;
            }
        }
        found.push(Found {
            file: file.to_owned(),
            line: t.line,
            context: context.to_owned(),
            msgid: ids_found[0].clone(),
            plural: ids_found.get(1).cloned(),
            comment,
        });
    }
    Ok((found, packaged))
}

/// The top-level, comma-separated arguments of a call whose `(` was just before `toks`.
fn split_args(toks: &[Token]) -> Option<Vec<Vec<Token>>> {
    let mut args: Vec<Vec<Token>> = vec![Vec::new()];
    let mut depth = 0usize;
    for t in toks {
        match t.tok {
            Tok::Punct('(' | '[' | '{') => depth += 1,
            Tok::Punct(')' | ']' | '}') => {
                if depth == 0 {
                    if args.last().is_some_and(Vec::is_empty) {
                        args.pop();
                    }
                    return Some(args);
                }
                depth -= 1;
            }
            Tok::Punct(',') if depth == 0 => {
                args.push(Vec::new());
                continue;
            }
            _ => {}
        }
        args.last_mut()?.push(t.clone());
    }
    None
}

/// The messages of all `files` as the text of a `.pot`, and the number of lookups of
/// packaged text. The same message found twice becomes one entry with both places.
fn rust_template(root: &Path, files: &[PathBuf]) -> Result<(String, usize)> {
    let mut all = Vec::new();
    let mut packaged = 0;
    for path in files {
        let name = rel(path);
        if RUST_SKIP.contains(&name.as_str()) {
            continue;
        }
        let src = std::fs::read_to_string(path)
            .with_context(|| format!("read {}", root.join(&name).display()))?;
        // Cheap test first: most files name no keyword.
        if !RUST_KEYWORDS.iter().any(|(k, _)| src.contains(k)) {
            continue;
        }
        let (found, p) = find_messages(&name, &src)?;
        all.extend(found);
        packaged += p;
    }
    let mut entries: Vec<Entry> = Vec::new();
    let mut index: BTreeMap<(String, String), usize> = BTreeMap::new();
    for f in all {
        let key = (f.context.clone(), f.msgid.clone());
        match index.get(&key) {
            Some(&i) => {
                let e = &mut entries[i];
                if e.plural != f.plural {
                    bail!(
                        "{}:{}: “{}” ({}) is a plural here and not elsewhere, or has another plural form",
                        f.file,
                        f.line,
                        f.msgid,
                        f.context
                    );
                }
                e.refs.push(format!("{}:{}", f.file, f.line));
                if let Some(c) = f.comment.filter(|c| !e.comments.contains(c)) {
                    e.comments.push(c);
                }
            }
            None => {
                index.insert(key, entries.len());
                entries.push(Entry {
                    refs: vec![format!("{}:{}", f.file, f.line)],
                    comments: f.comment.into_iter().collect(),
                    flags: Vec::new(),
                    context: Some(f.context),
                    msgid: f.msgid,
                    plural: f.plural,
                    strs: Vec::new(),
                });
            }
        }
    }
    let mut out = String::from(
        "msgid \"\"\nmsgstr \"\"\n\"Content-Type: text/plain; charset=UTF-8\\n\"\n\"Plural-Forms: nplurals=INTEGER; plural=EXPRESSION;\\n\"\n",
    );
    for e in &entries {
        out.push('\n');
        out.push_str(&e.to_po(2));
    }
    Ok((out, packaged))
}

