    #[test]
    fn po_text_round_trips() {
        let e = Entry {
            refs: vec!["a.rs:3".into()],
            comments: vec!["TRANSLATORS: x".into()],
            flags: vec!["kde-format".into()],
            context: Some("@info".into()),
            msgid: "a \"quoted\"\nline\\".into(),
            plural: Some("%1 b".into()),
            strs: vec![],
        };
        let text = format!("msgid \"\"\nmsgstr \"\"\n\n{}", e.to_po(2));
        let back = parse_po(&text).unwrap();
        assert_eq!(back[1].msgid, e.msgid);
        assert_eq!(back[1].context, e.context);
        assert_eq!(back[1].plural, e.plural);
        assert_eq!(back[1].strs, vec!["", ""]);
        assert_eq!(back[1].flags, e.flags);
        assert_eq!(back[1].comments, e.comments);
    }

    fn entry(context: Option<&str>, msgid: &str, plural: Option<&str>, strs: &[&str]) -> Entry {
        Entry {
            refs: vec!["crates/x.rs".into()],
            context: context.map(str::to_owned),
            msgid: msgid.into(),
            plural: plural.map(str::to_owned),
            strs: strs.iter().map(|s| (*s).to_owned()).collect(),
            ..Entry::default()
        }
    }

    #[test]
    fn the_template_rules_catch_what_the_project_forbids() {
        let header = entry(None, "", None, &[""]);
        let t = vec![
            header,
            entry(None, "No context", None, &[]),
            entry(Some("@info"), "Fine %1", None, &[]),
            entry(Some("@info"), "A <filename>x</filename>", None, &[]),
            entry(Some("@info"), "{n} files", None, &[]),
            entry(Some("info"), "No marker", None, &[]),
        ];
        let problems = template_problems(&t);
        assert_eq!(problems.len(), 4, "{problems:?}");
        assert!(problems[0].contains("no context"));
        assert!(problems[1].contains("KUIT"));
        assert!(problems[2].contains("placeholder"));
        assert!(problems[3].contains("marker"));
        // A string of the packaging files has no context, by gettext's convention.
        let mut packaged = entry(None, "Messenger", None, &[]);
        packaged.refs = vec!["packaging/app.desktop".into()];
        assert!(template_problems(&[entry(None, "", None, &[""]), packaged]).is_empty());
    }

    #[test]
    fn a_translation_keeps_the_placeholders_of_its_source() {
        let t = vec![
            entry(None, "", None, &[""]),
            entry(Some("@info"), "%1 and %2", None, &[]),
            entry(Some("@info"), "%1 file", Some("%1 files"), &[]),
        ];
        let good = vec![
            entry(None, "", None, &[""]),
            entry(Some("@info"), "%1 and %2", None, &["%2 und %1"]),
            // The form for one may say "one file" without the count.
            entry(
                Some("@info"),
                "%1 file",
                Some("%1 files"),
                &["eine Datei", "%1 Dateien"],
            ),
        ];
        assert!(translation_problems("de", &t, &good).is_empty());
        let bad = vec![
            entry(None, "", None, &[""]),
            entry(Some("@info"), "%1 and %2", None, &["%1 und"]),
            entry(
                Some("@info"),
                "%1 file",
                Some("%1 files"),
                &["%2 Datei", "%1 Dateien"],
            ),
        ];
        assert_eq!(translation_problems("de", &t, &bad).len(), 2);
    }

