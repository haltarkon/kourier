//! FIXED test certificates of the dial tests (TH3 call C7): DER bytes made ONCE, offline, on
//! 2026-10-25 with the `openssl` CLI (OpenSSL 3.0.13), never at test time and with no crate (`rcgen`
//! would add packages). Every key is P-256, every signature ECDSA with SHA-256; every certificate is
//! valid from 2026-01-01 00:00:00 to 2125-12-31 23:59:59 UTC ([`NOT_AFTER_S`]), so the tests give
//! the verifier a fixed time inside it (decision M7). The names are under `kourier.invalid` (RFC
//! 6761: never resolves). The private keys are TEST keys of these files only.
//!
//! How they were made (a CA config with `copy_extensions = none`, `default_md = sha256`, and the
//! extension sections named below; `D` = `-startdate 20260101000000Z -enddate 21251231235959Z`):
//!
//! ```text
//! openssl genpkey -algorithm EC -pkeyopt ec_paramgen_curve:P-256 -out <k>.key   # ca rogue leaf other
//! openssl req -new -key ca.key -subj "/CN=Kourier Test CA" -out ca.csr
//! openssl ca -batch -config ca.cnf -selfsign -keyfile ca.key -in ca.csr -extensions ext_ca $D -out ca.pem
//! openssl req -new -key rogue.key -subj "/CN=Kourier Unknown Test CA" -out rogue.csr
//! openssl ca -batch -config ca.cnf -selfsign -keyfile rogue.key -in rogue.csr -extensions ext_ca $D -out rogue.pem
//! openssl req -new -key leaf.key -subj "/CN=mediator-1.kourier.invalid" -out leaf.csr    # other.csr the same
//! openssl ca -batch -config ca.cnf -cert ca.pem -keyfile ca.key -in leaf.csr -extensions ext_leaf1 $D -out leaf.pem
//! openssl ca -batch -config ca.cnf -cert ca.pem -keyfile ca.key -in other.csr -extensions ext_leaf1 $D -out other.pem
//! openssl ca -batch -config ca.cnf -cert ca.pem -keyfile ca.key -in leaf.csr -extensions ext_leaf2 $D -out leaf_name2.pem
//! openssl ca -batch -config ca.cnf -cert rogue.pem -keyfile rogue.key -in leaf.csr -extensions ext_leaf1 $D -out leaf_rogue.pem
//! openssl x509 -in <c>.pem -outform der -out <c>.der
//! openssl pkcs8 -topk8 -nocrypt -in <k>.key -outform der -out <k>.key.der
//! openssl pkey -in <k>.key -pubout -outform der | sha256sum      # the SPKI hashes below
//! ```
//!
//! `ext_ca`: `basicConstraints = critical,CA:TRUE`, `keyUsage = critical,keyCertSign,cRLSign`,
//! `subjectKeyIdentifier = hash`. `ext_leaf1` / `ext_leaf2`: `basicConstraints = critical,CA:FALSE`,
//! `keyUsage = critical,digitalSignature`, `extendedKeyUsage = serverAuth`, `authorityKeyIdentifier =
//! keyid`, `subjectAltName = DNS:mediator-1.kourier.invalid` / `DNS:mediator-2.kourier.invalid`.

