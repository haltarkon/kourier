//! The protocol messages libthreema does not compile: `url-payloads.proto` (the payload of the join
//! URL, TH4). `build.rs` generates it onto libthreema's own `common` and `d2d_rendezvous` types, so a
//! `RendezvousInit` here IS libthreema's. Nothing in this module is public: no generated or
//! libthreema type is named by a public item of the crate.

/// `url-payloads.proto`, package `url`.
#[allow(
    clippy::all,
    clippy::pedantic,
    dead_code,
    missing_docs,
    rustdoc::broken_intra_doc_links,
    rustdoc::unescaped_backticks,
    reason = "code generated by prost"
)]
pub(crate) mod url {
    include!(concat!(env!("OUT_DIR"), "/url.rs"));
}

#[cfg(test)]
mod tests {
    use libthreema::protobuf::{common::Unit, d2d_rendezvous::RendezvousInit};
    use prost::Message as _;

    use super::url::{DeviceGroupJoinRequestOrOffer, device_group_join_request_or_offer as join};

    /// The generated message encodes and decodes, and its libthreema-typed fields are libthreema's
    /// (a `RendezvousInit` of the vendored copy sits inside it, no second copy was generated).
    #[test]
    fn a_join_request_encodes_and_decodes() {
        let init = RendezvousInit {
            version: libthreema::protobuf::d2d_rendezvous::rendezvous_init::Version::V10 as i32,
            ak: vec![0xa5; 32],
            relayed_web_socket: None,
            direct_tcp_server: None,
        };
        let request = DeviceGroupJoinRequestOrOffer {
            version: 0,
            d2d_protocol_version: 3,
            variant: Some(join::Variant {
                r#type: Some(join::variant::Type::RequestToJoin(Unit {})),
            }),
            rendezvous_init: Some(init),
        };
        let bytes = request.encode_to_vec();
        assert!(!bytes.is_empty(), "the message encodes to something");
        let back = DeviceGroupJoinRequestOrOffer::decode(bytes.as_slice()).expect("decodes");
        assert_eq!(back, request, "decoding gives the message back");
        assert_eq!(back.d2d_protocol_version, 3);
        assert_eq!(back.rendezvous_init.expect("init").ak, vec![0xa5; 32]);
    }
}
